-- 기존 수집 테이블이 있는 DB에 적용한다. 앱 시작 전에 실행한다.
BEGIN;

CREATE TABLE IF NOT EXISTS raw_normalization_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_record_id bigint NOT NULL REFERENCES raw_external_record(id),
    previous_raw_record_id bigint REFERENCES raw_external_record(id),
    event_type varchar(16) NOT NULL,
    status varchar(32) NOT NULL DEFAULT 'PENDING',
    created_at timestamptz NOT NULL,
    CONSTRAINT uk_normalization_request_raw UNIQUE (raw_record_id)
);

CREATE INDEX IF NOT EXISTS idx_normalization_request_status_id
    ON raw_normalization_request (status, id);

COMMIT;
