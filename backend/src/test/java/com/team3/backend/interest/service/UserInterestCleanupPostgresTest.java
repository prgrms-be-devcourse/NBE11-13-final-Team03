package com.team3.backend.interest.service;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;
import org.testcontainers.postgresql.PostgreSQLContainer;
import org.testcontainers.utility.MountableFile;

import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

/** 운영 DB 대신 별도 컨테이너에서 실제 psql 스크립트의 적용·롤백을 확인한다. */
@Tag("postgres")
@Testcontainers
class UserInterestCleanupPostgresTest {
    @Container
    static final PostgreSQLContainer POSTGRES = new PostgreSQLContainer("postgres:16-alpine");

    private JdbcTemplate jdbc;

    @BeforeEach
    void createDisposableSchema() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword()));
        jdbc.execute("""
                DROP SCHEMA IF EXISTS application CASCADE;
                CREATE SCHEMA application;
                CREATE TABLE application.user_interests (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id bigint NOT NULL, interest_type varchar(30) NOT NULL,
                    interest_code varchar(100) NOT NULL, created_at timestamp NOT NULL,
                    CONSTRAINT uk_user_interests_user_type_code UNIQUE(user_id, interest_type, interest_code)
                );
                CREATE TABLE application.opportunities (
                    id bigint PRIMARY KEY, current_version_id bigint, opportunity_type varchar(30),
                    category varchar(100), sub_category varchar(100), detail_category varchar(100)
                );
                CREATE TABLE application.opportunity_categories (
                    version_id bigint, large_category varchar(100), medium_category varchar(100)
                );
                INSERT INTO application.opportunities VALUES (1, 10, 'YOUTH_POLICY', NULL, NULL, NULL);
                INSERT INTO application.opportunity_categories VALUES (10, '일자리', '취업'), (10, '교육', '교육비지원');
                """);
        POSTGRES.copyFileToContainer(MountableFile.forClasspathResource(
                "db-boundary/user-interest-comma-cleanup.sql"), "/tmp/user-interest-comma-cleanup.sql");
    }

    @Test
    void previewDoesNotChangeExistingRows() throws Exception {
        add("CATEGORY", "일자리,교육");
        var result = script(false);
        assertThat(result.getExitCode()).isZero();
        assertThat(result.getStdout()).contains("일자리,교육", "ROLLBACK");
        assertThat(codes()).containsExactly("일자리,교육");
    }

    @Test
    void applySplitsAndDeduplicatesWhilePreservingDatesAndIsRepeatable() throws Exception {
        add("CATEGORY", "일자리, 교육");
        add("CATEGORY", "일자리");
        add("SUB_CATEGORY", "교육비지원,교육비지원");
        var result = script(true);
        assertThat(result.getExitCode()).withFailMessage(result.getStderr()).isZero();
        assertThat(codes()).containsExactlyInAnyOrder("일자리", "교육", "교육비지원");
        assertThat(jdbc.queryForObject("""
                SELECT count(*) FROM application.user_interests
                WHERE created_at = timestamp '2026-10-21 10:00:00'
                """, Integer.class)).isEqualTo(3);
        assertThat(script(true).getExitCode()).isZero();
        assertThat(codes()).hasSize(3);
    }

    @ParameterizedTest
    @ValueSource(strings = {"교육,없는분류", ",교육"})
    void unknownOrEmptyPartsRollBackWithoutDeletingTheSource(String code) throws Exception {
        add("CATEGORY", code);
        assertThat(script(true).getExitCode()).isNotZero();
        assertThat(codes()).containsExactly(code);
    }

    @Test
    void exceedingThirtyAfterSplittingRollsBack() throws Exception {
        for (int i = 0; i < 29; i++) {
            add("CATEGORY", "기존분야" + i);
        }
        add("CATEGORY", "일자리,교육");
        var result = script(true);
        assertThat(result.getExitCode()).isNotZero();
        assertThat(result.getStderr()).contains("30개");
        assertThat(codes()).hasSize(30).contains("일자리,교육").doesNotContain("일자리", "교육");
    }

    @Test
    void anActualCommaOptionRequiresManualReview() throws Exception {
        add("CATEGORY", "일자리,교육");
        jdbc.update("INSERT INTO application.opportunity_categories VALUES (10, '기계,조립', NULL)");
        var result = script(true);
        assertThat(result.getExitCode()).isNotZero();
        assertThat(result.getStderr()).contains("현재 선택지에 쉼표");
        assertThat(codes()).containsExactly("일자리,교육");
    }

    private void add(String type, String code) {
        jdbc.update("""
                INSERT INTO application.user_interests(user_id,interest_type,interest_code,created_at)
                VALUES (1, ?, ?, timestamp '2026-10-21 10:00:00')
                """, type, code);
    }

    private List<String> codes() {
        return jdbc.queryForList("SELECT interest_code FROM application.user_interests ORDER BY interest_code", String.class);
    }

    private org.testcontainers.containers.Container.ExecResult script(boolean apply) throws Exception {
        return POSTGRES.execInContainer("psql", "-U", POSTGRES.getUsername(), "-d", POSTGRES.getDatabaseName(),
                "-v", "apply=" + apply, "-f", "/tmp/user-interest-comma-cleanup.sql");
    }
}
