package com.team3.notification.fixture;

import java.nio.charset.StandardCharsets;
import java.sql.DriverManager;
import org.springframework.core.io.ClassPathResource;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.testcontainers.postgresql.PostgreSQLContainer;
import org.testcontainers.utility.MountableFile;

/** Operator SQL and restricted roles, with separate user/admin schema preparation. No shared container. */
public final class NotificationPostgres {
    public static final String PASSWORD = "test-only-notification-password";
    private NotificationPostgres() { }

    public static PostgreSQLContainer create() {
        return new PostgreSQLContainer("postgres:16-alpine")
                .withCopyFileToContainer(MountableFile.forClasspathResource("db-boundary/database-boundaries.sql"),
                        "/docker-entrypoint-initdb.d/01-boundaries.sql")
                .withCopyFileToContainer(MountableFile.forClasspathResource("db-test/passwords.sql"),
                        "/docker-entrypoint-initdb.d/02-test-passwords.sql");
    }

    public static void userSchema(PostgreSQLContainer postgres, DynamicPropertyRegistry registry) throws Exception {
        install(postgres, "notification-inbox.sql", "notification-user-api.sql", "notification-session-end.sql",
                "notification-withdrawal.sql", "notification-delivery.sql");
        try (var connection = DriverManager.getConnection(postgres.getJdbcUrl(), "notification_user", PASSWORD);
             var statement = connection.createStatement()) {
            // Entity exists only on the test classpath; never part of the deployed schema.
            statement.execute("CREATE TABLE notification.boundary_probe(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)");
        }
        registry.add("spring.datasource.url", postgres::getJdbcUrl);
        registry.add("spring.datasource.driver-class-name", postgres::getDriverClassName);
        registry.add("spring.datasource.username", () -> "notification_user");
        registry.add("spring.datasource.password", () -> PASSWORD);
        registry.add("spring.jpa.hibernate.ddl-auto", () -> "validate");
    }

    public static void adminSchema(PostgreSQLContainer postgres) throws Exception {
        install(postgres, "notification-inbox.sql", "notification-admin.sql");
    }

    private static void install(PostgreSQLContainer postgres, String... scripts) throws Exception {
        try (var connection = DriverManager.getConnection(postgres.getJdbcUrl(), "notification_user", PASSWORD);
             var statement = connection.createStatement()) {
            for (var script : scripts) {
                statement.execute(new ClassPathResource("db-boundary/" + script).getContentAsString(StandardCharsets.UTF_8));
            }
        }
    }
}
