BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
SET LOCAL search_path TO notification, pg_catalog;
DO $$ BEGIN
    IF current_user <> 'notification_user' THEN RAISE EXCEPTION 'Run notification-push-slots.sql as notification_user'; END IF;
END $$;
CREATE TABLE notification_push_bundles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    kst_date date NOT NULL,
    slot_no integer NOT NULL CHECK (slot_no BETWEEN 1 AND 3),
    window_start timestamptz NOT NULL,
    window_end timestamptz NOT NULL CHECK (window_end > window_start),
    representative_notification_id bigint NOT NULL REFERENCES notifications(id) ON DELETE CASCADE,
    policy_version varchar(80) NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('READY','COMPLETED','SKIPPED','FAILED')),
    first_attempt_at timestamptz,
    created_at timestamptz NOT NULL,
    closed_at timestamptz,
    UNIQUE (user_id, kst_date, slot_no)
);
CREATE TABLE notification_push_pending (
    notification_id bigint PRIMARY KEY REFERENCES notifications(id) ON DELETE CASCADE,
    user_id bigint NOT NULL,
    priority integer CHECK (priority IS NULL OR priority BETWEEN 0 AND 6),
    status varchar(20) NOT NULL CHECK (status IN ('PENDING','BUNDLED','SKIPPED')),
    bundle_id bigint REFERENCES notification_push_bundles(id) ON DELETE CASCADE,
    reason varchar(80),
    created_at timestamptz NOT NULL,
    CHECK ((status = 'BUNDLED') = (bundle_id IS NOT NULL AND reason IS NULL))
);
CREATE INDEX idx_push_pending_user ON notification_push_pending(user_id, priority, notification_id) WHERE status = 'PENDING';
CREATE TABLE notification_push_slot_usage (
    user_id bigint NOT NULL,
    kst_date date NOT NULL,
    slot_no integer NOT NULL CHECK (slot_no BETWEEN 1 AND 3),
    bundle_id bigint NOT NULL UNIQUE REFERENCES notification_push_bundles(id) ON DELETE CASCADE,
    first_attempt_at timestamptz NOT NULL,
    PRIMARY KEY (user_id, kst_date, slot_no)
);
CREATE TABLE notification_bundle_deliveries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bundle_id bigint NOT NULL REFERENCES notification_push_bundles(id) ON DELETE CASCADE,
    endpoint_id bigint NOT NULL REFERENCES notification_endpoints(id) ON DELETE CASCADE,
    user_id bigint NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('PENDING','CLAIMED','SENDING','SENT','SKIPPED','FAILED')),
    retry_count integer NOT NULL DEFAULT 0 CHECK (retry_count >= 0),
    next_retry_at timestamptz NOT NULL,
    processing_started_at timestamptz,
    lease_token uuid,
    sent_at timestamptz,
    fcm_message_id varchar(500),
    last_error varchar(80),
    created_at timestamptz NOT NULL,
    UNIQUE (bundle_id, endpoint_id),
    CHECK ((status IN ('CLAIMED','SENDING') AND lease_token IS NOT NULL AND processing_started_at IS NOT NULL)
        OR (status NOT IN ('CLAIMED','SENDING') AND lease_token IS NULL AND processing_started_at IS NULL))
);
CREATE INDEX idx_bundle_delivery_retry ON notification_bundle_deliveries(status, next_retry_at, id);
CREATE INDEX idx_push_bundle_expiry ON notification_push_bundles(window_end, id) WHERE status = 'READY';
COMMIT;
