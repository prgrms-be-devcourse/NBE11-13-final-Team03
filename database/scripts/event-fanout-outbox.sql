-- Apply once AFTER date-tracking.sql, while Application workers are stopped.
-- Run as application_user; existing policy/event/scan data is preserved.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL search_path TO application, pg_catalog;

DO $$
BEGIN
    IF current_user <> 'application_user' THEN
        RAISE EXCEPTION 'Run event-fanout-outbox.sql as application_user';
    END IF;
END $$;

ALTER TABLE opportunity_events
    ADD COLUMN lease_token uuid,
    ADD COLUMN last_user_id bigint NOT NULL DEFAULT 0,
    ADD COLUMN fanout_skip_reason varchar(80);
ALTER TABLE opportunity_events ADD CONSTRAINT ck_event_last_user_nonnegative CHECK(last_user_id >= 0);
CREATE INDEX idx_opportunity_events_lease ON opportunity_events(processing_status, processing_started_at);

CREATE TABLE outbox_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id uuid NOT NULL,
    dedup_key varchar(200) NOT NULL,
    event_type varchar(40) NOT NULL,
    user_id bigint NOT NULL,
    source_event_id uuid,
    opportunity_id bigint,
    notification_type varchar(40),
    payload jsonb NOT NULL,
    status varchar(30) NOT NULL,
    retry_count integer NOT NULL,
    next_retry_at timestamptz NOT NULL,
    processing_started_at timestamptz,
    lease_token uuid,
    published_at timestamptz,
    last_error text,
    created_at timestamptz NOT NULL,
    CONSTRAINT uk_outbox_message_id UNIQUE(message_id),
    CONSTRAINT uk_outbox_dedup_key UNIQUE(dedup_key)
);
CREATE INDEX idx_outbox_status_retry ON outbox_events(status, next_retry_at);
-- No User/Opportunity FK: future USER_WITHDRAWN requests must survive user deletion.
COMMIT;
