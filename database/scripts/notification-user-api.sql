-- Apply once as notification_user, after notification-inbox.sql and before the new service boots.
BEGIN;
SET LOCAL search_path TO notification;
DO $$ BEGIN
    IF current_user <> 'notification_user' THEN
        RAISE EXCEPTION 'Run this script as notification_user';
    END IF;
END $$;

CREATE TABLE notification_settings (
    user_id bigint PRIMARY KEY CHECK (user_id > 0),
    in_app_enabled boolean NOT NULL DEFAULT true,
    push_enabled boolean NOT NULL DEFAULT false,
    push_consent_at timestamptz,
    updated_at timestamptz NOT NULL,
    CONSTRAINT ck_notification_settings_push_consent CHECK (push_enabled = (push_consent_at IS NOT NULL))
);
CREATE TABLE notification_endpoints (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL CHECK (user_id > 0),
    fcm_token varchar(2048) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uk_notification_endpoints_fcm_token UNIQUE (fcm_token)
);
CREATE INDEX idx_notification_endpoints_user_active ON notification_endpoints(user_id, active);
CREATE INDEX idx_notifications_user_id ON notifications(user_id, id DESC);
CREATE INDEX idx_notifications_user_unread ON notifications(user_id) WHERE read_at IS NULL;
COMMIT;
