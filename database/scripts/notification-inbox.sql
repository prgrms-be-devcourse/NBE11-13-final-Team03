-- Apply once as notification_user after database-boundaries.sql.
-- Stop Notification during rollout. No Application table/permission is changed.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL search_path TO notification, pg_catalog;

DO $$
BEGIN
    IF current_user <> 'notification_user' THEN
        RAISE EXCEPTION 'Run notification-inbox.sql as notification_user';
    END IF;
END $$;

CREATE TABLE notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    source_event_id uuid NOT NULL,
    message_id uuid NOT NULL,
    correlation_id uuid NOT NULL,
    causation_id uuid NOT NULL,
    opportunity_id bigint NOT NULL,
    opportunity_version_id bigint NOT NULL,
    type varchar(40) NOT NULL,
    title varchar(500) NOT NULL,
    content text NOT NULL,
    link varchar(2000) NOT NULL,
    payload jsonb NOT NULL,
    occurred_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL,
    read_at timestamptz,
    clicked_at timestamptz,
    CONSTRAINT uk_notifications_user_source_event UNIQUE(user_id, source_event_id)
);
CREATE INDEX idx_notifications_user_created ON notifications(user_id, created_at, id);

CREATE TABLE consumed_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id uuid NOT NULL,
    user_id bigint NOT NULL,
    source_event_id uuid NOT NULL,
    correlation_id uuid NOT NULL,
    request_fingerprint varchar(64) NOT NULL,
    result varchar(30) NOT NULL,
    notification_id bigint,
    consumed_at timestamptz NOT NULL,
    CONSTRAINT uk_consumed_messages_message_id UNIQUE(message_id),
    CONSTRAINT fk_consumed_notification FOREIGN KEY(notification_id)
        REFERENCES notifications(id) ON DELETE SET NULL
);
CREATE INDEX idx_consumed_user_source ON consumed_messages(user_id, source_event_id);

COMMIT;
