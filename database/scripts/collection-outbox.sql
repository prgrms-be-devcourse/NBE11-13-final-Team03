-- Apply once as application_user BEFORE starting the new data-service version (including fresh DBs).
-- Provision application_user/application first using database-boundaries.sql.
-- Do not let ddl-auto:update create this table first: it cannot install the CHECK/defaults below.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL search_path TO application, pg_catalog;

DO $$
BEGIN
    IF current_user <> 'application_user' THEN
        RAISE EXCEPTION 'Run collection-outbox.sql as application_user';
    END IF;
END $$;

CREATE TABLE collection_outbox_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id uuid NOT NULL,
    dedup_key varchar(120) NOT NULL,
    event_type varchar(40) NOT NULL,
    sync_job_id bigint NOT NULL,
    payload jsonb NOT NULL,
    status varchar(30) NOT NULL DEFAULT 'PENDING',
    retry_count integer NOT NULL DEFAULT 0,
    next_retry_at timestamptz NOT NULL,
    processing_started_at timestamptz,
    lease_token uuid,
    published_at timestamptz,
    last_error text,
    created_at timestamptz NOT NULL,
    CONSTRAINT uk_collection_outbox_message_id UNIQUE(message_id),
    CONSTRAINT uk_collection_outbox_dedup_key UNIQUE(dedup_key),
    CONSTRAINT ck_collection_outbox_event_type CHECK(event_type = 'COLLECTION_COMPLETED'),
    CONSTRAINT ck_collection_outbox_status CHECK(status IN ('PENDING', 'PROCESSING', 'PUBLISHED', 'FAILED')),
    CONSTRAINT ck_collection_outbox_retry_count CHECK(retry_count >= 0)
);
CREATE INDEX idx_collection_outbox_status_retry ON collection_outbox_events(status, next_retry_at);
-- No User/job FK: this message has no recipient ID and survives history cleanup.
COMMIT;
