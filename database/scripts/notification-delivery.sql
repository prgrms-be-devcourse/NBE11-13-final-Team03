-- Apply once as notification_user after inbox, user-api and withdrawal DDL, with Notification stopped.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL search_path TO notification, pg_catalog;
DO $$ BEGIN
    IF current_user <> 'notification_user' THEN
        RAISE EXCEPTION 'Run notification-delivery.sql as notification_user';
    END IF;
END $$;
ALTER TABLE notifications ADD COLUMN in_app_visible boolean NOT NULL DEFAULT true;
-- Fresh databases include the optional push expiry; existing databases use notification-push-expiry.sql.
ALTER TABLE notifications ADD COLUMN push_expires_at timestamptz;
CREATE TABLE notification_deliveries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id bigint NOT NULL,
    endpoint_id bigint NOT NULL,
    user_id bigint NOT NULL,
    status varchar(30) NOT NULL,
    retry_count integer NOT NULL DEFAULT 0 CHECK (retry_count >= 0),
    next_retry_at timestamptz NOT NULL,
    processing_started_at timestamptz,
    lease_token uuid,
    sent_at timestamptz,
    fcm_message_id varchar(500),
    last_error varchar(80),
    created_at timestamptz NOT NULL,
    CONSTRAINT uk_delivery_notification_endpoint UNIQUE (notification_id, endpoint_id),
    CONSTRAINT fk_delivery_notification FOREIGN KEY (notification_id) REFERENCES notifications(id) ON DELETE CASCADE,
    CONSTRAINT fk_delivery_endpoint FOREIGN KEY (endpoint_id) REFERENCES notification_endpoints(id) ON DELETE CASCADE,
    CONSTRAINT ck_delivery_status CHECK (status IN ('PENDING','SENDING','SENT','SKIPPED','FAILED')),
    CONSTRAINT ck_delivery_lease CHECK ((status = 'SENDING') = (lease_token IS NOT NULL AND processing_started_at IS NOT NULL))
);
CREATE INDEX idx_delivery_status_retry ON notification_deliveries(status, next_retry_at, id);
CREATE INDEX idx_delivery_user ON notification_deliveries(user_id);
COMMIT;
