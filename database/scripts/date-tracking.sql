-- Apply once as application_user after the Application base tables exist.
-- Stop the Application during rollout. This does not reset or update existing tables.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL search_path TO application, pg_catalog;

DO $$
BEGIN
    IF current_user <> 'application_user' THEN
        RAISE EXCEPTION 'Run date-tracking.sql as application_user';
    END IF;
END $$;

CREATE TABLE event_scan_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_date date NOT NULL,
    status varchar(20) NOT NULL,
    execution_id varchar(36) NOT NULL,
    started_at timestamptz NOT NULL,
    completed_at timestamptz,
    retry_count integer NOT NULL,
    last_error text,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uk_event_scan_history_scan_date UNIQUE (scan_date)
);
CREATE INDEX idx_event_scan_history_status_date ON event_scan_history(status, scan_date);

CREATE TABLE opportunity_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id uuid NOT NULL,
    correlation_id uuid NOT NULL,
    opportunity_id bigint NOT NULL CONSTRAINT fk_opportunity_events_opportunity
        REFERENCES application.opportunities(id),
    opportunity_version_id bigint NOT NULL CONSTRAINT fk_opportunity_events_version
        REFERENCES application.opportunity_versions(id),
    event_type varchar(40) NOT NULL,
    event_date date NOT NULL,
    dedup_key varchar(500) NOT NULL,
    payload jsonb NOT NULL,
    notification_eligible boolean NOT NULL,
    suppression_reason varchar(50),
    processing_status varchar(30) NOT NULL,
    processing_started_at timestamptz,
    retry_count integer NOT NULL,
    next_retry_at timestamptz NOT NULL,
    last_error text,
    processed_at timestamptz,
    occurred_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL,
    CONSTRAINT uk_opportunity_events_event_id UNIQUE(event_id),
    CONSTRAINT uk_opportunity_events_dedup_key UNIQUE(dedup_key)
);
CREATE INDEX idx_opportunity_events_processing ON opportunity_events(processing_status, next_retry_at);
CREATE INDEX idx_opportunity_events_opportunity ON opportunity_events(opportunity_id);
CREATE INDEX idx_opportunity_events_event_date ON opportunity_events(event_date);

COMMIT;
